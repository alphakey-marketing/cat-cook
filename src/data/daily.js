// 冇 SAY 嘅（⚠️ 只聽）場景，開場主角句用 word 聲
// 精簡格式 → 場景。「用」一步嘅錯誤選項：喺同話題抽遠啲嘅主角句（意思唔同）
function build(raw, cat) {
  const speak = raw.filter((r) => !r.warn);
  const n = speak.length;
  return raw.map((r) => {
    // ls／ctx／re 跟寫嘅先後次序出
    const turns = [];
    for (const k of Object.keys(r)) {
      if (k === 'ls') turns.push(LS(r.ls[0], r.ls[1], r.ls[5] || '👂 佢講咩？', r.ls[2], [r.ls[3], r.ls[4]]));
      if (k === 'ctx') r.ctx.forEach(([jp, yue]) => turns.push(F(jp, yue)));
      if (k === 're') turns.push(ME(r.re[0], L(r.re[1], r.re[2]), r.re.slice(3).map((x) => L(...x))));
    }
    if (!r.warn && n > 3) {
      const i = speak.indexOf(r);
      const others = [speak[(i + Math.floor(n / 3)) % n], speak[(i + Math.floor((2 * n) / 3)) % n]];
      turns.push(ME(`💬 ${r.when}，你會講？`, L(r.k[0], r.k[1]),
        others.map((o) => L(o.k[0], o.k[1], `呢句意思係「${o.k[1]}」，唔啱呢個情境`))));
      turns.push(SAY(r.k[0], r.k[1]));
    }
    return {
      id: `${cat}${r.n}`, n: r.n, cat, lv: r.lv, name: r.name, icon: r.icon, rel: r.rel || 'friend', topic: 'feeling',
      key: r.k[0], intro: r.intro, warn: r.warn, turns,
      points: [{ jp: r.k[0], yue: r.k[1] }, ...(r.pt || []).map(([jp, yue]) => ({ jp, yue }))],
    };
  });
}

HAND.forEach((sc, i) => { sc.cat = 'n'; sc.n = String(i + 1).padStart(3, '0'); });
export const DAILY = [...HAND, ...build([...N1, ...N2, ...N3, ...N4], 'n'), ...build([...K1, ...K2], 'k'), ...build([...L1, ...L2, ...L3, ...L4, ...L5], 'l')];

