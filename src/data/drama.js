// 俾語音腳本：朋友 usagi、你 cat
export function dramaLines() {
  const out = [];
  for (const sc of DRAMA) {
    for (const t of sc.turns) {
      if (t.t === 'f' || t.t === 'ls') out.push({ jp: t.line.jp, voice: 'usagi' });
      if (t.t === 'me') { out.push({ jp: t.ok.jp, voice: 'cat' }); t.bad.forEach((b) => out.push({ jp: b.jp, voice: 'cat' })); }
    }
  }
  return out;
}
