// 俾語音腳本：角色句用 NPC 聲、你嘅句用 cat、語言點用 word
export function sceneLines(list) {
  const out = [];
  for (const sc of list) {
    for (const t of sc.turns) {
      const v = NPC[t.rel || sc.rel];
      if (t.t === 'f' || t.t === 'ls') out.push({ jp: t.line.jp, voice: v });
      if (t.t === 'me') { out.push({ jp: t.ok.jp, voice: 'cat' }); t.bad.forEach((b) => out.push({ jp: b.jp, voice: 'cat' })); }
      if (t.t === 'say') out.push({ jp: t.line.jp, voice: 'cat' });
      if (t.t === 'ch') t.opts.forEach((o) => { out.push({ jp: o.jp, voice: 'cat' }); if (o.re) out.push({ jp: o.re.jp, voice: v }); });
      if (t.t === 'end') [...t.good.lines, ...t.bad.lines].forEach((l) => out.push({ jp: l.jp, voice: v }));
    }
    sc.points.forEach((p) => { if (/[ぁ-んァ-ン]/.test(p.jp)) out.push({ jp: p.jp, voice: 'word' }); });
  }
  return out;
}
export function dramaLines() {
  const out = sceneLines(DRAMA);
  REGISTER.forEach((r) => REG_REL.forEach((k) => out.push({ jp: r[k], voice: 'cat' })));
  return out;
}
